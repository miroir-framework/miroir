"""Rename the published workspace packages to their @miroir-framework/* names (#650).

One rule, with exceptions: an old package name (scripts/package-rename-map.json) standing as a whole word is a
reference to the package and is renamed: an import specifier (with or without a subpath), a manifest key or `name`,
a `-w` / `--workspace` selector, a quoted name in a config, list or policy file, a mention in a living doc. Kept:
- a name inside a longer word or path (`packages/miroir-core`, `unit-miroir-core`, `_miroir-core_` logger names,
  `miroir-core.instances`): the word boundaries exclude them;
- a name followed by a folder of the package (`miroir-core/src/...`, `/dist/`, `/tests/`, ...): a folder path;
- files and lines of scripts/package-rename-allow.json: names that are not npm names (logger `packageName`,
  MiroirTest `functionRef.module` ids, bin and root-script names, folder lists of build scripts, ...);
- skipped trees: history (code-helpers/features, docs-OLD, changelogs), the lockfile (regenerated by npm), generated
  copies, test results.

Idempotent: a renamed reference starts with `@miroir-framework/`, which the word boundaries never match again.

    python scripts/rename_packages.py --report     # counts by name and context, and every occurrence to review
    python scripts/rename_packages.py --apply      # rename in place
    python scripts/rename_packages.py --check      # exit 1 when an old name is left outside the allow-list
"""

from __future__ import annotations

import argparse
import collections
import fnmatch
import json
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAP_FILE = ROOT / "scripts" / "package-rename-map.json"
ALLOW_FILE = ROOT / "scripts" / "package-rename-allow.json"

SKIPPED = [
    "code-helpers/**",
    "docs-OLD/**",
    "**/CHANGELOG*.md",
    "package-lock.json",
    ".claude/skills/**",
    "test-results/**",
    "graphify-out/**",
    "scripts/package-rename-map.json",
    "scripts/package-rename-allow.json",
    "scripts/rename_packages.py",
    "scripts/tests/test_rename_packages.py",
    "docs/reference/core-public-api.md",
    "scripts/tests/test_check_dependency_policy.py",
    "scripts/tests/test_fill_lockfile_integrity.py",
    "scripts/tests/fixtures/**",
]
FOLDER_SUBPATH = re.compile(r"/(?:src|dist|tests|scripts|assets|node_modules|release|public|certs|tmp|\.miroir)\b")
TEXT_SUFFIXES = {
    ".ts", ".tsx", ".mts", ".cts", ".js", ".jsx", ".mjs", ".cjs", ".json", ".md", ".py", ".sh", ".yml", ".yaml",
    ".html", ".txt", ".toml", ".cfg", ".ini", ".env", ".css", "",
}


@dataclass(frozen=True)
class Occurrence:
    path: str
    line: int
    name: str
    kind: str  # "renamed:<context>", "kept:<context>", "allowed:<reason>", "folder-path"
    text: str


def load_map(map_file: Path = MAP_FILE) -> dict[str, str]:
    return json.loads(map_file.read_text(encoding="utf-8"))


def load_allow(allow_file: Path = ALLOW_FILE) -> list[dict]:
    return json.loads(allow_file.read_text(encoding="utf-8")) if allow_file.is_file() else []


def name_pattern(mapping: dict[str, str]) -> re.Pattern[str]:
    names = sorted(mapping, key=len, reverse=True)
    return re.compile(r"(?<![\w.@/-])(" + "|".join(map(re.escape, names)) + r")(?![\w-]|\.\w)")


def matches_glob(path: str, patterns: list[str]) -> bool:
    return any(fnmatch.fnmatch(path, pattern) for pattern in patterns)


def allowed_reason(path: str, line_text: str, allow: list[dict]) -> str | None:
    for entry in allow:
        if not matches_glob(path, entry.get("files", ["**"])):
            continue
        pattern = entry.get("line")
        if pattern is None or re.search(pattern, line_text):
            return entry["reason"]
    return None


# commands as well as packages: a bare mention is the command (`miroir-env prune`), so only specifier contexts rename
BIN_NAMES = {"miroir-env", "miroir-cli"}
QUOTES = "'\"`"
SELECTOR_BEFORE = re.compile(r"(?:^|[\s(`])(?:-w|--workspace|-e|npm\s+ls)(?:=|\s+)$")


def context_of(line_text: str, start: int, end: int) -> str:
    """"quoted" for a whole specifier between quotes (with or without a subpath), "selector" after -w / --workspace,
    else "bare"."""
    before = line_text[start - 1] if start > 0 else ""
    if before == "!" and start > 1 and line_text[start - 2] in QUOTES:
        before = line_text[start - 2]  # an nx negation: "!miroir-core"
    if before and before in QUOTES:
        close = end
        if close < len(line_text) and line_text[close] == "/":
            while close < len(line_text) and line_text[close] not in QUOTES and not line_text[close].isspace():
                close += 1
        if close < len(line_text) and line_text[close] == before:
            return "quoted"
    if SELECTOR_BEFORE.search(line_text[:start]):
        return "selector"
    return "bare"


def renames(path: str, name: str, context: str) -> bool:
    if context in {"quoted", "selector"}:
        return True
    return path.endswith(".md") and name not in BIN_NAMES


def scan(path: str, text: str, mapping: dict[str, str], allow: list[dict]) -> tuple[list[Occurrence], str]:
    """The occurrences of old names in a file, and its text with the renamed ones replaced."""
    pattern = name_pattern(mapping)
    occurrences: list[Occurrence] = []
    out: list[str] = []
    for number, line_text in enumerate(text.splitlines(keepends=True), start=1):
        pieces: list[str] = []
        last = 0
        for match in pattern.finditer(line_text):
            name = match.group(1)
            context = context_of(line_text, match.start(), match.end())
            reason = allowed_reason(path, line_text, allow)
            if FOLDER_SUBPATH.match(line_text, match.end()):
                kind = "folder-path"
            elif reason is not None:
                kind = f"allowed:{reason}"
            elif not renames(path, name, context):
                kind = f"kept:{context}"
            else:
                kind = f"renamed:{context}"
                pieces.append(line_text[last : match.start()])
                pieces.append(mapping[name])
                last = match.end()
            occurrences.append(Occurrence(path, number, name, kind, line_text.strip()))
        pieces.append(line_text[last:])
        out.append("".join(pieces))
    return occurrences, "".join(out)


def tracked_files(root: Path) -> list[str]:
    result = subprocess.run(["git", "ls-files"], cwd=root, capture_output=True, text=True, check=False)
    if result.returncode == 0:
        return result.stdout.splitlines()
    return [p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file() and ".git" not in p.parts]


def candidate_files(root: Path) -> list[str]:
    return [
        path
        for path in tracked_files(root)
        if Path(path).suffix in TEXT_SUFFIXES and not matches_glob(path, SKIPPED) and (root / path).is_file()
    ]


def run(root: Path, mapping: dict[str, str], allow: list[dict], apply: bool) -> list[Occurrence]:
    occurrences: list[Occurrence] = []
    for path in candidate_files(root):
        file = root / path
        try:
            text = file.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        found, renamed = scan(path, text, mapping, allow)
        occurrences += found
        if apply and renamed != text:
            file.write_text(renamed, encoding="utf-8")
    return occurrences


def report(occurrences: list[Occurrence]) -> str:
    by_kind = collections.Counter(o.kind for o in occurrences)
    by_name = collections.Counter(o.name for o in occurrences if o.kind.startswith("renamed"))
    files = collections.Counter(o.path.split("/")[0] for o in occurrences if o.kind.startswith("renamed"))
    lines = ["# Package-name references (#650)", "", "Generated by `python scripts/rename_packages.py --report`.", ""]
    lines += ["## By kind", "", "| Kind | Occurrences |", "|---|---|"]
    lines += [f"| {kind} | {count} |" for kind, count in by_kind.most_common()]
    lines += ["", "## Renamed, by name", "", "| Name | Occurrences |", "|---|---|"]
    lines += [f"| `{name}` | {count} |" for name, count in by_name.most_common()]
    lines += ["", "## Renamed, by top-level folder", "", "| Folder | Occurrences |", "|---|---|"]
    lines += [f"| `{folder}` | {count} |" for folder, count in files.most_common()]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--report", action="store_true")
    group.add_argument("--apply", action="store_true")
    group.add_argument("--check", action="store_true")
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    parser.add_argument("--list", choices=["renamed", "kept", "allowed", "folder-path"], help="with --report: list occurrences")
    args = parser.parse_args(argv)
    root: Path = args.root
    mapping = load_map(root / "scripts" / "package-rename-map.json")
    allow = load_allow(root / "scripts" / "package-rename-allow.json")
    occurrences = run(root, mapping, allow, apply=args.apply)
    renamed = [o for o in occurrences if o.kind.startswith("renamed")]
    if args.report:
        if args.list:
            for o in occurrences:
                if o.kind.startswith(args.list):
                    print(f"{o.path}:{o.line}: [{o.kind}] {o.text[:160]}")
        else:
            sys.stdout.write(report(occurrences))
        return 0
    if args.apply:
        print(f"renamed {len(renamed)} references in {len({o.path for o in renamed})} files")
        return 0
    if renamed:
        for o in renamed:
            print(f"{o.path}:{o.line}: {o.name}: {o.text[:160]}")
        print(f"{len(renamed)} references to old package names: run python scripts/rename_packages.py --apply")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
