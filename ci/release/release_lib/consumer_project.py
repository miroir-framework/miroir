"""#658: the out-of-workspace consumer test.

A project generated by `@miroir-framework/create-app`, in a folder outside the repository, installed from the packed
tarballs only, must type-check, build, start its server on the filesystem store, serve its client and answer a REST
request. Analysis and plan: code-helpers/features/658-FEATURE-create-app-consumer-test/.
"""

from __future__ import annotations

import json
import os
import shutil
import socket
import subprocess
import tempfile
import time
import urllib.error
import urllib.request
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Iterator

from release_lib.common import ReleaseError, dump_json, executable, load_json, log_step, npm_pack_entries, run
from release_lib.workspace import release_closure, workspace_packages

GENERATOR = "@miroir-framework/create-app"
SCOPE = "@miroir-framework/"
MIROIR_DEPLOYMENT = "10ff36f2-50a3-48d8-b80f-e48e5d13af8e"
ENTITY_ENTITY = "16dbfe28-e1d7-4f20-9ba4-c1a9873202ad"
ENTITY_LIST_PATH = f"/CRUD/{MIROIR_DEPLOYMENT}/model/entity/{ENTITY_ENTITY}/all"
# #645: the warning core prints when a second copy of it is loaded
DUPLICATE_CORE_WARNING = "copies are loaded in this realm"
SERVER_START_TIMEOUT_SECONDS = 180


def template_manifest(repo_root: Path) -> dict:
    return load_json(repo_root / "packages/miroir-create-app/template/package.json")


def required_packages(repo_root: Path) -> list[str]:
    """The generator and the workspace packages a generated project installs, with their runtime closure."""
    packages = workspace_packages(repo_root)
    template = template_manifest(repo_root)
    direct = {
        name
        for field in ("dependencies", "devDependencies")
        for name in template.get(field, {})
        if name.startswith(SCOPE)
    }
    unknown = direct - set(packages)
    if unknown:
        raise ReleaseError("the template depends on unknown workspace package(s): " + ", ".join(sorted(unknown)))
    return sorted(release_closure(direct | {GENERATOR}, packages))


def missing_tarballs(repo_root: Path, tarballs: dict[str, Path]) -> list[str]:
    return [name for name in required_packages(repo_root) if name not in tarballs]


def tarballs_from_manifest(repo_root: Path, tarball_dir: Path) -> dict[str, Path]:
    """The tarballs of a `release-tarballs/` folder written by `pack_layer`, by package name."""
    manifest_path = tarball_dir / "manifest.json"
    if not manifest_path.is_file():
        raise ReleaseError(f"{manifest_path} not found: not a folder written by release_version.py --apply")
    found: dict[str, Path] = {}
    for info in load_json(manifest_path).get("tarballs", []):
        recorded = Path(info["path"])
        # the tarball beside the manifest first (a kept or moved folder), then the recorded path (relative to the
        # repository root): another build of the same version may have rewritten the latter
        candidates = [tarball_dir / recorded.parent.name / recorded.name, repo_root / recorded]
        path = next((candidate for candidate in candidates if candidate.is_file()), None)
        if path is None:
            raise ReleaseError(f"tarball of {info['package']} not found: {recorded}")
        found[info["package"]] = path.resolve()
    return found


def pack_workspace(repo_root: Path, destination: Path) -> dict[str, Path]:
    """`npm pack` of the built workspace packages a generated project needs (versions as in the workspace)."""
    packages = workspace_packages(repo_root)
    destination.mkdir(parents=True, exist_ok=True)
    found: dict[str, Path] = {}
    for name in required_packages(repo_root):
        folder = packages[name].path.parent
        result = run(
            [executable("npm"), "pack", "--json", "--ignore-scripts", "--pack-destination", str(destination)],
            cwd=folder,
            check=False,
            announce=False,
        )
        if result.returncode != 0:
            raise ReleaseError(f"npm pack failed for {name}:\n{result.stderr or result.stdout}")
        found[name] = (destination / npm_pack_entries(result.stdout)[0]["filename"]).resolve()
        log_step(f"  packed {name} -> {found[name].name}")
    return found


def file_spec(path: Path) -> str:
    return f"file:{path.resolve().as_posix()}"


def rewrite_dependencies(manifest: dict, tarballs: dict[str, Path]) -> dict:
    """Points every Miroir dependency of a generated project at its tarball: the direct ones in `dependencies` /
    `devDependencies`, every other packed one (server → mcp) through `overrides`, so npm never asks the registry."""
    rewritten = json.loads(json.dumps(manifest))
    for field in ("dependencies", "devDependencies"):
        for name in rewritten.get(field, {}):
            if not name.startswith(SCOPE):
                continue
            if name not in tarballs:
                raise ReleaseError(f"no tarball for {name}, a dependency of the generated project")
            rewritten[field][name] = file_spec(tarballs[name])
    rewritten["overrides"] = {
        **rewritten.get("overrides", {}),
        **{name: file_spec(path) for name, path in sorted(tarballs.items()) if name != GENERATOR},
    }
    return rewritten


def npm(project: Path, *args: str) -> None:
    result = run([executable("npm"), *args], cwd=project, check=False)
    if result.returncode != 0:
        raise ReleaseError(f"npm {' '.join(args)} failed in {project}:\n{result.stdout[-4000:]}\n{result.stderr[-4000:]}")


def prepare_project(tarballs: dict[str, Path], work_dir: Path) -> Path:
    """Generates the project with the generator's tarball, points it at the tarballs, installs, type-checks and
    builds it. Returns the project folder."""
    if GENERATOR not in tarballs:
        raise ReleaseError(f"no tarball for {GENERATOR}")
    project = work_dir / "miroir-consumer-app"
    log_step(f"consumer test: generating a project in {project}")
    result = run(
        [executable("npm"), "exec", "--yes", f"--package={file_spec(tarballs[GENERATOR])}", "--", "create-app", str(project)],
        cwd=work_dir,
        check=False,
    )
    if result.returncode != 0:
        raise ReleaseError(f"create-app failed:\n{result.stdout}\n{result.stderr}")
    manifest_path = project / "package.json"
    dump_json(manifest_path, rewrite_dependencies(load_json(manifest_path), tarballs))
    npm(project, "install", "--no-audit", "--no-fund")
    npm(project, "run", "typecheck")
    npm(project, "run", "build")
    return project


def free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
        probe.bind(("127.0.0.1", 0))
        return probe.getsockname()[1]


def get(url: str, timeout: float = 30) -> tuple[int, str]:
    try:
        with urllib.request.urlopen(url, timeout=timeout) as response:
            return response.status, response.read().decode("utf-8", errors="replace")
    except urllib.error.HTTPError as error:
        return error.code, error.read().decode("utf-8", errors="replace")


@dataclass
class RunningServer:
    base_url: str
    output_file: Path

    def output(self) -> str:
        return self.output_file.read_text(encoding="utf-8", errors="replace")


@contextmanager
def started_server(project: Path) -> Iterator[RunningServer]:
    """`npm start` on a free port; stopped on exit. Fails when the port does not answer, or when core warns that
    two copies of it are loaded (#645)."""
    port = free_port()
    output_file = project / "server-output.log"
    env = {key: value for key, value in os.environ.items() if not key.startswith("MIROIR_")}
    env["PORT"] = str(port)
    with output_file.open("w", encoding="utf-8") as output:
        process = subprocess.Popen(
            [executable("node"), "dist-server/server.js"], cwd=project, env=env, stdout=output, stderr=subprocess.STDOUT
        )
    server = RunningServer(base_url=f"http://127.0.0.1:{port}", output_file=output_file)
    try:
        deadline = time.monotonic() + SERVER_START_TIMEOUT_SECONDS
        while True:
            if process.poll() is not None:
                raise ReleaseError(f"the generated server exited with code {process.returncode}:\n{server.output()}")
            try:
                with socket.create_connection(("127.0.0.1", port), timeout=1):
                    break
            except OSError:
                if time.monotonic() > deadline:
                    raise ReleaseError(f"the generated server did not listen on {port}:\n{server.output()}")
                time.sleep(0.5)
        if DUPLICATE_CORE_WARNING in server.output():
            raise ReleaseError(f"two copies of core are loaded in the generated server:\n{server.output()}")
        log_step(f"consumer test: server listening at {server.base_url}")
        yield server
    finally:
        process.terminate()
        try:
            process.wait(timeout=15)
        except subprocess.TimeoutExpired:
            process.kill()


def check_entity_list(base_url: str) -> None:
    """The Miroir deployment's Entity list holds the Entity entity."""
    status, body = get(base_url + ENTITY_LIST_PATH)
    if status != 200:
        raise ReleaseError(f"GET {ENTITY_LIST_PATH}: status {status}\n{body[:2000]}")
    if ENTITY_ENTITY not in body:
        raise ReleaseError(f"GET {ENTITY_LIST_PATH}: no Entity {ENTITY_ENTITY} in the answer\n{body[:2000]}")


def check_client(base_url: str) -> None:
    """The server serves the built client, also for a client-side route."""
    for path in ("/", "/a/client/route"):
        status, body = get(base_url + path)
        if status != 200 or '<div id="root">' not in body or '<script type="module"' not in body:
            raise ReleaseError(f"GET {path}: not the built client (status {status})\n{body[:2000]}")


def run_consumer_project(tarballs: dict[str, Path], *, keep: bool = False) -> None:
    """The whole consumer test, in a temporary folder outside the repository."""
    work_dir = Path(tempfile.mkdtemp(prefix="miroir-consumer-project-"))
    try:
        project = prepare_project(tarballs, work_dir)
        with started_server(project) as server:
            check_entity_list(server.base_url)
            check_client(server.base_url)
        log_step("consumer test: passed")
    finally:
        if keep:
            log_step(f"consumer test: project kept in {work_dir}")
        else:
            shutil.rmtree(work_dir, ignore_errors=True)
